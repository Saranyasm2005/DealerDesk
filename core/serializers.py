from decimal import Decimal
import re
from rest_framework import serializers

from core.models import Product, Dealer, Order, OrderItem
from core.utils import format_money


class ProductSerializer(serializers.ModelSerializer):
    price = serializers.SerializerMethodField()
    stock = serializers.IntegerField(read_only=True)

    class Meta:
        model = Product
        fields = [
            "sku",
            "name",
            "category",
            "brand",
            "vehicle_fitment",
            "price",
            "stock",
            "description",
        ]

    def get_price(self, obj) -> str:
        return format_money(obj.price)


class ProductCreateSerializer(serializers.ModelSerializer):
    price = serializers.CharField()

    class Meta:
        model = Product
        fields = [
            "sku",
            "name",
            "category",
            "brand",
            "vehicle_fitment",
            "price",
            "description",
        ]

    def validate_price(self, value):
        # Must be positive amount with at most 2 decimal places
        if not re.match(r"^\d+(\.\d{1,2})?$", str(value).strip()):
            raise serializers.ValidationError("Price must be a positive number with at most 2 decimal places")
        val = Decimal(str(value).strip())
        if val <= Decimal("0.00"):
            raise serializers.ValidationError("Price must be greater than zero")
        return val


